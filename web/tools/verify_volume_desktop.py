"""Read Wasm-created VDB files and generate the paired desktop reference."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
from prepare import ROOT


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--blender', default='blender')
    args = parser.parse_args()
    directory = ROOT / 'web/tests/fixtures/volume'
    directory.mkdir(parents=True, exist_ok=True)
    for name in ('sphere-zip.vdb', 'sphere-blosc.vdb'):
        shutil.copy2(ROOT / 'build/native/volume-fixtures' / name, directory / name)
    reference = directory / 'reference.json'
    command = [args.blender, '--background', '--factory-startup', '--threads', '8',
               '--python-exit-code', '1', '--python-expr',
               f"import runpy,json; scope=runpy.run_path('web/tests/volume.py'); result=scope['run']({str(directory)!r},'build/native/volume-native-cache'); open({str(reference)!r},'w').write(json.dumps(result,sort_keys=True)+'\\n'); print('VOLUME_DESKTOP_DONE')"]
    result = subprocess.run(command, cwd=ROOT, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    (ROOT / 'build/native/volume-desktop.log').write_text(result.stdout)
    result.check_returncode()
    report = json.loads(reference.read_text())
    assert report['blenderVersion'].split()[0] == json.loads((ROOT / 'web/upstream.json').read_text())['blenderVersion']
    report['workloadSha256'] = hashlib.sha256((ROOT / 'web/tests/volume.py').read_bytes()).hexdigest()
    reference.write_text(json.dumps(report, sort_keys=True) + '\n')
    hashes = {path.name:hashlib.sha256(path.read_bytes()).hexdigest()
              for path in sorted(directory.iterdir()) if path.suffix in ('.vdb', '.json')}
    (directory / 'README.txt').write_text(
        "VDB fixtures generated by the original OpenVDB 13.0.0 Wasm build.\n"
        "Both archives contain a float level-set sphere and a float fog-density sphere.\n"
        "Compression: ZIP and Blosc, both with active-value masks.\n"
        "reference.json records original desktop Blender volume modifier evaluations.\n"
        "Regenerate with native_build.py --check-deps, then verify_volume_desktop.py.\n"
        + json.dumps(hashes, indent=2) + '\n')
    print(json.dumps({name:{key:value for key,value in case.items() if key != 'positions'}
                      for name,case in report['cases'].items()}))


if __name__ == '__main__':
    main()
